#!/usr/bin/env python3
"""Crew migration: six named crew (Dr. Safaa, Noor, Dr. Alaa, Abdulaziz, Ahmed, Mostafa)
plus NEXO, the colony robot, who takes over the greenhouse and comms-tower duties of the two
unnamed engineer roles. Idempotent: running it twice changes nothing."""
import json, pathlib
root = pathlib.Path('/home/ubuntu/Luna-Quest')
OLD = {'npc_agriculture_engineer': 'agri', 'npc_comms_software_engineer': 'comms'}
NEXO = 'npc_nexo'

def load(p): return json.loads((root / p).read_text(encoding='utf-8'))
def save(p, d): (root / p).write_text(json.dumps(d, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')

# ---- npcs.json ---------------------------------------------------------------------
npcs = load('content/npcs.json')
old = {n['id']: n for n in npcs['npcs'] if n['id'] in OLD}
npcs['npcs'] = [n for n in npcs['npcs'] if n['id'] not in OLD and n['id'] != NEXO]
def sched(s, e, loc, en, ar): return {'start': s, 'end': e, 'location': loc, 'activityEn': en, 'activityAr': ar}
nexo = {
    'id': NEXO,
    'nameEn': 'NEXO',
    'nameAr': 'نيكسو',
    'nameStatus': 'approved',
    'isRobot': True,
    'roleEn': 'Colony Robot — Greenhouse and Comms Tower',
    'roleAr': 'روبوت المستعمرة — الدفيئة وبرج الاتصالات',
    'locationId': 'greenhouse',
    'skills': ['Hydroponics telemetry', 'Antenna and relay checks', 'Sensor calibration', 'Data logging'],
    'traits': ['literal', 'cheerful', 'never guesses', 'logs everything'],
    'knownSystems': sorted(set(old.get('npc_agriculture_engineer', {}).get('knownSystems', ['crops', 'food']) +
                               old.get('npc_comms_software_engineer', {}).get('knownSystems', ['comms', 'network', 'relay']))),
    'relationships': ['npc_nour', 'npc_ahmed'],
    'storySeedEn': 'NEXO floats beside the commander, runs the greenhouse and the relay remotely, and refuses to report a number it has not measured.',
    'storySeedAr': 'يطفو نيكسو بجانب القائد، ويدير الدفيئة والمرحل عن بُعد، ويرفض الإبلاغ عن رقم لم يقِسه.',
    'boundaryEn': 'NEXO is a fictional assistant robot. Real lunar surface robots are teleoperated or semi-autonomous and far slower.',
    'greetingEn': 'Commander! Greenhouse nominal, relay nominal. I measured both. I did not guess.',
    'greetingAr': 'أيها القائد! الدفيئة سليمة والمرحل سليم. قستُ الاثنين ولم أخمّن.',
    'schedule': [
        sched(0, 3, 'greenhouse', 'night crop rounds', 'جولة المحاصيل الليلية'),
        sched(3, 5, 'garage', 'charging', 'شحن'),
        sched(5, 12, 'greenhouse', 'crop climate control', 'التحكم بمناخ المحاصيل'),
        sched(12, 18, 'comms_tower', 'relay alignment', 'محاذاة المرحل'),
        sched(18, 24, 'greenhouse', 'harvest logging', 'تسجيل الحصاد'),
    ],
    'responsibilitiesEn': 'Keeps the greenhouse lights, water and nutrients logged, checks the antenna and relay, and helps the commander read the colony.',
    'responsibilitiesAr': 'يسجّل إضاءة الدفيئة ومياهها ومغذياتها، ويفحص الهوائي والمرحل، ويساعد القائد على قراءة المستعمرة.',
}
npcs['npcs'].append(nexo)
for n in npcs['npcs']:
    n['relationships'] = [r for r in n.get('relationships', []) if r not in OLD]
    if n['id'] == 'npc_nour' and NEXO not in n['relationships']: n['relationships'].append(NEXO)
    if n['id'] == 'npc_ahmed' and NEXO not in n['relationships']: n['relationships'].append(NEXO)
npcs['comment'] = 'Six named crew members plus NEXO, the colony robot. The commander is the player.'
save('content/npcs.json', npcs)

# ---- dialogue.json -----------------------------------------------------------------
KEEP = {'light', 'crop_water', 'stress', 'harvest', 'link', 'antenna', 'data', 'earth'}
dia = load('content/dialogue.json')
topics = []
for t in dia['topics']:
    if t['npcId'] in OLD:
        if t['id'] not in KEEP: continue
        t = dict(t); t['npcId'] = NEXO
        t['voiceKey'] = 'talk.nexo.' + t['id']
    topics.append(t)
dia['topics'] = topics
save('content/dialogue.json', dia)

# ---- incidents.json ----------------------------------------------------------------
inc = load('content/incidents.json')
key = [k for k in inc if isinstance(inc[k], list)][0]
for i in inc[key]:
    if i.get('owner') in OLD: i['owner'] = NEXO
save('content/incidents.json', inc)

# ---- voices.json -------------------------------------------------------------------
v = load('content/voices.json')
for o in OLD: v['cast'].pop(o, None)
v['cast'][NEXO] = {'prefix': 'nexo', 'model': 'generated-robot', 'lengthScale': 1.0, 'noiseScale': 0.6,
                   'note': 'Pre-rendered with a robot voice filter; not regenerated by Piper.'}
NEXO_LINES = {
    'crew.nexo.greet': (nexo['greetingEn'], nexo['greetingAr']),
    'bark.nexo.0': ('Greenhouse humidity sixty-two percent. Leaves are happy. I asked them.', 'رطوبة الدفيئة اثنان وستون بالمئة. الأوراق سعيدة. سألتُها.'),
    'bark.nexo.1': ('Relay drift is zero point two degrees. Small numbers become big problems.', 'انحراف المرحل اثنتان من عشرة درجة. الأرقام الصغيرة تصبح مشكلات كبيرة.'),
    'bark.nexo.2': ('Oxygen stays on. Science can wait. That is rule number one.', 'الأكسجين يبقى يعمل. العلم يمكنه الانتظار. هذه القاعدة الأولى.'),
    'bark.nexo.3': ('Plan your power, Commander. Then face the day.', 'خطّط لطاقتك أيها القائد. ثم واجه اليوم.'),
}
lines = []
for l in v['lines']:
    if l['speaker'] in OLD:
        if l['key'].startswith('inc.'):
            l = dict(l); l['speaker'] = NEXO; lines.append(l)
        continue
    if l['speaker'] == NEXO and l['key'] in NEXO_LINES: continue
    lines.append(l)
for k, (en, ar) in NEXO_LINES.items():
    lines.append({'key': k, 'speaker': NEXO, 'text': en, 'textAr': ar})
v['lines'] = lines
save('content/voices.json', v)

# ---- learning.json wording -----------------------------------------------------------
lp = root / 'content/learning.json'
s = lp.read_text(encoding='utf-8')
s = s.replace('nine crew still lose water', 'seven people still lose water').replace('يفقد تسعة أفراد', 'يفقد سبعة أفراد')
lp.write_text(s, encoding='utf-8')
print('migrated:', [n['id'] for n in npcs['npcs']], 'topics', len(topics))
